// Package an explicitly built frontend. This script never runs a frontend build.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, mkdirSync, mkdtempSync, copyFileSync, writeFileSync, unlinkSync, statSync, symlinkSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJSON = (path) => JSON.parse(readFileSync(join(root, path), 'utf8'));
const version = readJSON('package.json').version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Packaging requires a stable semantic version');
for (const file of ['apps/desktop/package.json', 'apps/web/package.json', 'packages/schema/package.json']) {
  if (readJSON(file).version !== version) throw new Error(`Version mismatch: ${file}`);
}
const platform = process.platform;
const arch = process.arch === 'x64' ? 'amd64' : process.arch;
if (!['win32', 'darwin'].includes(platform) || !['amd64', 'arm64'].includes(arch)) {
  throw new Error(`Unsupported packaging host: ${platform}/${arch}`);
}
const index = readFileSync(join(root, 'apps/web/out/index.html'), 'utf8');
if (!index.includes('name="niceenv-desktop-bridge" content="1"')) throw new Error('Wails frontend assets are missing or obsolete');
const releaseDir = join(root, 'artifacts/release');
mkdirSync(releaseDir, { recursive: true });
const stage = mkdtempSync(join(releaseDir, `${platform}-${arch}-`));
const assets = join(root, 'apps/desktop/assets');
const env = { ...process.env, GOOS: platform === 'win32' ? 'windows' : 'darwin', GOARCH: arch };
const run = (program, args) => {
  const result = spawnSync(program, args, { cwd: root, env, stdio: 'inherit', shell: false });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${program} failed (${result.status})`);
};
const ldflags = `-s -w -X main.version=${version} -X niceenv/internal/core.BuildChannel=production`;
const executable = platform === 'win32' ? 'NiceEnv.exe' : 'NiceEnv';
const cli = platform === 'win32' ? 'nsbctl.exe' : 'nsbctl';
const mcp = platform === 'win32' ? 'nsb-mcp.exe' : 'nsb-mcp';
let bin = stage;
let output;
if (platform === 'darwin') {
  bin = join(stage, 'NiceEnv.app/Contents/MacOS');
  mkdirSync(bin, { recursive: true });
}
const syso = join(root, `cmd/niceenv/wails_windows_${arch}.syso`);
if (platform === 'win32') {
  if (existsSync(syso)) throw new Error(`Resource file already exists; inspect it before retrying: ${syso}`);
  const info = { fixed: { file_version: version }, info: { '0000': {
    ProductVersion: version, CompanyName: 'nsmao-com', FileDescription: 'NiceEnv',
    LegalCopyright: 'Copyright nsmao-com', ProductName: 'NiceEnv',
  } } };
  writeFileSync(join(stage, 'info.json'), JSON.stringify(info));
}
try {
  if (platform === 'win32') {
    run(process.env.WAILS3 || 'wails3', ['generate', 'syso', '-arch', arch, '-icon', join(assets, 'icon.ico'),
      '-manifest', join(root, 'packaging/windows/app.manifest'), '-info', join(stage, 'info.json'), '-out', syso]);
  }
  run('go', ['build', '-mod=readonly', '-trimpath', '-tags', 'production,desktopassets', '-ldflags',
    `${ldflags}${platform === 'win32' ? ' -H windowsgui' : ''}`, '-o', join(bin, executable), './cmd/niceenv']);
} finally {
  // Only remove the resource generated by this invocation; never clean source directories.
  if (platform === 'win32' && existsSync(syso)) unlinkSync(syso);
}
run('go', ['build', '-mod=readonly', '-trimpath', '-ldflags', ldflags, '-o', join(bin, cli), './cmd/niceenv-cli']);
copyFileSync(join(bin, cli), join(bin, mcp));
if (platform === 'win32') {
  const tools = join(stage, 'wails-assets');
  run(process.env.WAILS3 || 'wails3', ['generate', 'webview2bootstrapper', '-dir', tools]);
  output = join(releaseDir, `NiceEnv_${version}_windows_${arch}_setup.exe`);
  const makensis = process.env.MAKENSIS || ['C:/Program Files (x86)/NSIS/makensis.exe', 'C:/Program Files/NSIS/makensis.exe'].find(existsSync) || 'makensis';
  run(makensis, ['-V3', `-DVERSION=${version}`, `-DARCH=${arch}`, `-DSTAGE=${stage}`, `-DOUTPUT=${output}`,
    `-DICON=${join(assets, 'icon.ico')}`, `-DBOOTSTRAPPER=${join(tools, 'MicrosoftEdgeWebview2Setup.exe')}`,
    `-DINSTALL_SIZE=${Math.ceil([executable, cli, mcp].reduce((sum, file) => sum + statSync(join(bin, file)).size, 0) / 1024)}`,
    join(root, 'packaging/windows/installer.nsi')]);
} else {
  const contents = join(stage, 'NiceEnv.app/Contents');
  mkdirSync(join(contents, 'Resources'));
  copyFileSync(join(assets, 'icon.icns'), join(contents, 'Resources/icon.icns'));
  writeFileSync(join(contents, 'Info.plist'), readFileSync(join(root, 'packaging/darwin/Info.plist'), 'utf8').replaceAll('@VERSION@', version));
  const identity = process.env.APPLE_SIGNING_IDENTITY || '-';
  for (const file of [cli, mcp, executable]) run('codesign', ['--force', '--sign', identity, ...(identity === '-' ? [] : ['--options', 'runtime', '--timestamp']), join(bin, file)]);
  run('codesign', ['--force', '--sign', identity, ...(identity === '-' ? [] : ['--options', 'runtime', '--timestamp']), join(stage, 'NiceEnv.app')]);
  run('codesign', ['--verify', '--deep', '--strict', join(stage, 'NiceEnv.app')]);
  symlinkSync('/Applications', join(stage, 'Applications'));
  output = join(releaseDir, `NiceEnv_${version}_macos_${arch}.dmg`);
  if (existsSync(output)) throw new Error(`Installer already exists: ${output}`);
  run('hdiutil', ['create', '-volname', 'NiceEnv', '-srcfolder', stage, '-ov', '-format', 'UDZO', output]);
}
const sha = createHash('sha256').update(readFileSync(output)).digest('hex');
writeFileSync(`${output}.sha256`, `${sha}  ${output.slice(releaseDir.length + 1)}\n`);
console.log(`Packaged ${output}`);
