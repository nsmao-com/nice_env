package systempath

import (
	"errors"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

type Snapshot struct {
	Path    string
	Value   string
	Kind    uint32
	Exists  bool
	Fixture bool
}

func Same(a, b string) bool {
	if runtime.GOOS == "windows" {
		a = strings.TrimRight(strings.ReplaceAll(strings.Trim(strings.TrimSpace(a), "\""), "/", "\\"), "\\")
		b = strings.TrimRight(strings.ReplaceAll(strings.Trim(strings.TrimSpace(b), "\""), "/", "\\"), "\\")
		return strings.EqualFold(a, b)
	}
	return strings.TrimRight(a, "/") == strings.TrimRight(b, "/")
}
func Contains(paths []string, path string) bool {
	for _, p := range paths {
		if Same(p, path) {
			return true
		}
	}
	return false
}
func MergeWindows(value string, previous, desired []string) string {
	parts := []string{}
	current := strings.Split(value, ";")
	for _, dir := range desired {
		if !Contains(parts, dir) && (!Contains(current, dir) || Contains(previous, dir)) {
			parts = append(parts, dir)
		}
	}
	if value != "" {
		for _, part := range strings.Split(value, ";") {
			if !Contains(previous, part) {
				parts = append(parts, part)
			}
		}
	}
	return strings.Join(parts, ";")
}

const begin = "# BEGIN NiceEnv (managed PATH)"
const end = "# END NiceEnv (managed PATH)"

func quote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'" }
func profileBlock(dirs []string) string {
	if len(dirs) == 0 {
		return ""
	}
	return begin + "\nexport PATH=" + quote(strings.Join(dirs, ":")) + ":\"$PATH\"\n" + end + "\n"
}
func profileMarkers(line string) int {
	switch strings.TrimSpace(line) {
	case begin, "# BEGIN NiceServBay (managed PATH)":
		return 1
	case end, "# END NiceServBay (managed PATH)":
		return -1
	}
	return 0
}
func MergeProfile(value string, dirs []string) (string, error) {
	lines := strings.SplitAfter(value, "\n")
	inside := false
	written := false
	var out strings.Builder
	for _, line := range lines {
		switch profileMarkers(line) {
		case 1:
			if inside {
				return "", errors.New("shell PATH 托管标记嵌套，未修改配置")
			}
			inside = true
			if !written {
				out.WriteString(profileBlock(dirs))
				written = true
			}
		case -1:
			if !inside {
				return "", errors.New("shell PATH 托管结束标记缺少开始标记")
			}
			inside = false
		default:
			if !inside {
				out.WriteString(line)
			}
		}
	}
	if inside {
		return "", errors.New("shell PATH 托管块缺少结束标记，未修改配置")
	}
	if !written && len(dirs) > 0 {
		if value != "" && !strings.HasSuffix(value, "\n") {
			out.WriteByte('\n')
		}
		out.WriteString(profileBlock(dirs))
	}
	return out.String(), nil
}
func Entries(snapshot Snapshot) []string {
	if runtime.GOOS == "windows" || snapshot.Fixture {
		if snapshot.Value == "" {
			return []string{}
		}
		return strings.Split(snapshot.Value, ";")
	}
	// The block is generated by NiceEnv; split only its literal prefix. Never
	// evaluate shell syntax or expand arbitrary user profile code.
	inside := false
	for _, line := range strings.Split(snapshot.Value, "\n") {
		switch profileMarkers(line) {
		case 1:
			inside = true
		case -1:
			inside = false
		default:
			if inside && strings.HasPrefix(line, "export PATH=") {
				value := strings.TrimPrefix(line, "export PATH=")
				suffix := ":\"$PATH\""
				if strings.HasSuffix(value, suffix) {
					literal := strings.TrimSuffix(value, suffix)
					if strings.HasPrefix(literal, "'") && strings.HasSuffix(literal, "'") {
						decoded := strings.ReplaceAll(literal[1:len(literal)-1], "'\"'\"'", "'")
						return strings.Split(decoded, ":")
					}
				}
			}
		}
	}
	return []string{}
}

func ReadFixture(path string) ([]Snapshot, error) {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return []Snapshot{{Path: path, Fixture: true}}, nil
	}
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Size() > 1024*1024 {
		return nil, errors.New("PATH 隔离文件无效")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return []Snapshot{{Path: path, Value: string(data), Exists: true, Fixture: true}}, nil
}
func writeFileSnapshot(before Snapshot, value string) error {
	current, err := os.ReadFile(before.Path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if (err == nil) != before.Exists || string(current) != before.Value {
		return errors.New("PATH 配置已被其它程序修改，请重新读取")
	}
	if info, err := os.Lstat(before.Path); err == nil && !info.Mode().IsRegular() {
		return errors.New("shell 配置不能是链接或目录")
	}
	mode := os.FileMode(0600)
	if info, err := os.Stat(before.Path); err == nil {
		mode = info.Mode().Perm()
		if mode&0200 == 0 {
			return errors.New("shell 配置为只读")
		}
	}
	f, err := os.CreateTemp(filepath.Dir(before.Path), ".niceenv-path-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if err = f.Chmod(mode); err != nil {
		f.Close()
		return err
	}
	_, writeErr := f.WriteString(value)
	syncErr := f.Sync()
	closeErr := f.Close()
	if err = errors.Join(writeErr, syncErr, closeErr); err != nil {
		return err
	}
	current, err = os.ReadFile(before.Path)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if (err == nil) != before.Exists || string(current) != before.Value {
		return errors.New("PATH 配置在保存前发生变化")
	}
	if !before.Exists {
		return os.Link(f.Name(), before.Path)
	}
	return os.Rename(f.Name(), before.Path)
}
func Apply(before []Snapshot, previous, desired []string) ([]Snapshot, error) {
	after := []Snapshot{}
	for _, snapshot := range before {
		var value string
		var err error
		if runtime.GOOS == "windows" || snapshot.Fixture {
			value = MergeWindows(snapshot.Value, previous, desired)
		} else {
			value, err = MergeProfile(snapshot.Value, desired)
		}
		if err == nil && value != snapshot.Value {
			if snapshot.Fixture || runtime.GOOS != "windows" {
				err = writeFileSnapshot(snapshot, value)
			} else {
				err = writeSystem(snapshot, value)
			}
		}
		if err != nil {
			restoreErr := Restore(before[:len(after)], after)
			return nil, errors.Join(err, restoreErr)
		}
		next := snapshot
		next.Value = value
		if value != snapshot.Value {
			next.Exists = true
		}
		after = append(after, next)
	}
	return after, nil
}
func Restore(before, after []Snapshot) error {
	var failures []error
	for i := len(after) - 1; i >= 0; i-- {
		if before[i].Value == after[i].Value && before[i].Exists == after[i].Exists {
			continue
		}
		var err error
		if after[i].Fixture || runtime.GOOS != "windows" {
			if before[i].Exists {
				err = writeFileSnapshot(after[i], before[i].Value)
			} else {
				current, readErr := ReadFixture(after[i].Path)
				if readErr != nil {
					err = readErr
				} else if !current[0].Exists || current[0].Value != after[i].Value {
					err = errors.New("PATH 配置在恢复前发生变化，未删除")
				} else {
					err = os.Remove(after[i].Path)
				}
			}
		} else {
			err = restoreSystem(after[i], before[i])
		}
		if err != nil {
			failures = append(failures, err)
		}
	}
	return errors.Join(failures...)
}
